    jsx, links = convert(body_of(html), route_of)
    # collapse the blank runs the source carries between sections
    jsx = re.sub(r'\n{3,}', '\n\n', jsx).strip()
    jsx = '\n'.join('      ' + l.strip() if l.strip() else '' for l in jsx.split('\n'))
