#!/usr/bin/env python3
"""Build src/gv-au.css from the nine AU design pages.

Same split as gv-v3.css: a selector whose body is identical on every page it
appears on becomes one global `.v3 ...` rule; a selector that differs by page
is emitted once per page under `.v3.p-<key>`. Flattening the differing ones is
the bug that made every .com hero render at runtime's 120px.
"""
import re, pathlib, collections, sys

SRC = pathlib.Path('/Users/jjayaraj/Downloads/GovernVeil-website-AU/site-au')
PAGES = [('index','home'),('platform','platform'),('how-it-works','howitworks'),
         ('agents','agents'),('runtime','runtime'),('security','security'),
         ('benchmark','benchmark'),('partners','pilot'),('about','about')]

def blocks(html):
    return re.findall(r'<style[^>]*>(.*?)</style>', html, re.S)

def strip_comments(css):
    return re.sub(r'/\*.*?\*/', '', css, flags=re.S)

def split_rules(css):
    """Brace-depth aware. Yields (prelude, body) where body may itself hold
    rules (for @media). A flat regex lifts @media inner rules to top level —
    that bug made the mobile overrides apply at every width."""
    out, depth, buf, prelude = [], 0, '', None
    for ch in css:
        if ch == '{':
            depth += 1
            if depth == 1:
                prelude, buf = buf.strip(), ''
                continue
        elif ch == '}':
            depth -= 1
            if depth == 0:
                out.append((prelude, buf))
                buf = ''
                continue
        buf += ch
    return out

def scope(sel, page=None):
    """`.v3` or `.v3.p-<page>` in front of each comma-separated selector."""
    root = '.v3' if page is None else f'.v3.p-{page}'
    parts = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s in (':root', 'html', 'body', '*'):
            parts.append(root)
        elif s.startswith(('@', ':root')):
            parts.append(s)
        else:
            parts.append(f'{root} {s}')
    return ', '.join(parts)

# selector -> page -> body, keeping first-seen order
top   = collections.OrderedDict()
media = collections.OrderedDict()   # condition -> selector -> page -> body

for fname, key in PAGES:
    css = '\n'.join(blocks((SRC/f'{fname}.html').read_text()))
    for prelude, body in split_rules(strip_comments(css)):
        if prelude.startswith('@media'):
            cond = re.sub(r'\s+', ' ', prelude).strip()
            for s2, b2 in split_rules(body):
                media.setdefault(cond, collections.OrderedDict()) \
                     .setdefault(s2, collections.OrderedDict())[key] = re.sub(r'\s+',' ',b2).strip().strip(';')
        elif prelude.startswith('@'):
            # @font-face, @keyframes etc: keep verbatim, dedup by text
            media.setdefault('__raw__', collections.OrderedDict()) \
                 .setdefault(prelude, collections.OrderedDict())[key] = re.sub(r'\s+',' ',body).strip()
        else:
            top.setdefault(prelude, collections.OrderedDict())[key] = re.sub(r'\s+',' ',body).strip().strip(';')

def emit(table):
    shared, perpage = [], []
    for sel, bodies in table.items():
        if len(set(bodies.values())) == 1:
            shared.append(f'{scope(sel)}{{{next(iter(bodies.values()))}}}')
        else:
            for page, body in bodies.items():
                perpage.append(f'{scope(sel, page)}{{{body}}}')
    return shared, perpage

s_top, p_top = emit(top)

out = ["""/* Iteration 4 — governveil.com.au, ported from the design's site-au/.

   GENERATED by tools/aucss.py from the nine <style> blocks in
   GovernVeil-website-AU/site-au/. Do not hand-edit: the next regeneration
   overwrites it. Shell rules (header, mega-menu, footer) live in
   gv-au-shell.css, which is hand-written for exactly that reason.

   Each design page sets its own .h1x/.h2x/.pair, so a selector is global only
   when every page agrees on its body; the rest are scoped to `.v3.p-<page>`
   and ShellAU stamps the key on the root. */
""",
 '/* shared — identical on every AU page */'] + s_top

if p_top:
    out += ['', '/* per page — the design gives these different values per page */'] + p_top

for cond, table in media.items():
    if cond == '__raw__':
        for prelude, bodies in table.items():
            out += ['', f'{prelude}{{{next(iter(bodies.values()))}}}']
        continue
    s_m, p_m = emit(table)
    if s_m or p_m:
        out += ['', f'{cond}{{'] + ['  '+r for r in s_m+p_m] + ['}']

dest = pathlib.Path('/Users/jjayaraj/workspaces/studios/governveil-website/src/gv-au.css')
dest.write_text('\n'.join(out) + '\n')
print(f'wrote {dest}  {len(s_top)} shared, {len(p_top)} page-scoped, '
      f'{sum(1 for c in media if c!="__raw__")} media blocks')
