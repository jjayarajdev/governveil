import { Routes, Route, Navigate, useLocation } from 'react-router-dom'
import { useEffect } from 'react'
import ShellAU from './gv/au/ShellAU'
import HomeAU from './gv/au/HomeAU'
import PlatformAU from './gv/au/PlatformAU'
import HowItWorksAU from './gv/au/HowItWorksAU'
import AgentsAU from './gv/au/AgentsAU'
import RuntimeAU from './gv/au/RuntimeAU'
import SecurityAU from './gv/au/SecurityAU'
import BenchmarkAU from './gv/au/BenchmarkAU'
import PilotAU from './gv/au/PilotAU'
import AboutAU from './gv/au/AboutAU'
/* unlisted, reached only from the printed card — see gv/au/unlisted.js */
import DemoAU from './gv/au/DemoAU'
import ConnectAU from './gv/au/ConnectAU'

/* governveil.com.au. A separate entry from the .com app rather than a
   hostname branch inside it: the two sites have different page sets
   (security and partners here, trust and pilot there) and different copy
   throughout, so sharing one bundle would ship each audience the other's
   site and put an `if (au)` in every page. What they do share is the design
   system — gv-v3-shell.css is not loaded, but Logo.jsx is, and gv-au.css is
   generated by the same scoping rule as gv-v3.css. */

/* The static hand-off links *.html; anyone who saved one of those paths
   lands on the route it became. */
const LEGACY = {
  '/index.html': '/', '/platform.html': '/platform',
  '/how-it-works.html': '/how-it-works', '/agents.html': '/agents',
  '/runtime.html': '/runtime', '/security.html': '/security',
  '/benchmark.html': '/benchmark', '/partners.html': '/pilot',
  '/about.html': '/about',
  /* the .com names, for anyone arriving from the other site */
  '/product': '/how-it-works', '/mcp': '/agents', '/guard': '/runtime',
  '/trust': '/security',
  /* /partners was the live path for a day before the rename */
  '/partners': '/pilot',
}

function ScrollToTop() {
  const { pathname, hash } = useLocation()
  useEffect(() => {
    if (hash) {
      document.getElementById(hash.slice(1))?.scrollIntoView({ behavior: 'smooth' })
    } else {
      window.scrollTo(0, 0)
    }
  }, [pathname, hash])
  return null
}

export default function AppAU() {
  return (
    <ShellAU>
      <ScrollToTop />
      <Routes>
        <Route path="/" element={<HomeAU />} />
        <Route path="/platform" element={<PlatformAU />} />
        <Route path="/how-it-works" element={<HowItWorksAU />} />
        <Route path="/agents" element={<AgentsAU />} />
        <Route path="/runtime" element={<RuntimeAU />} />
        <Route path="/security" element={<SecurityAU />} />
        <Route path="/benchmark" element={<BenchmarkAU />} />
        <Route path="/pilot" element={<PilotAU />} />
        <Route path="/about" element={<AboutAU />} />
        <Route path="/demo" element={<DemoAU />} />
        <Route path="/connect" element={<ConnectAU />} />
        {Object.entries(LEGACY).map(([from, to]) => (
          <Route key={from} path={from} element={<Navigate to={to} replace />} />
        ))}
        <Route path="*" element={<Navigate to="/" replace />} />
      </Routes>
    </ShellAU>
  )
}
